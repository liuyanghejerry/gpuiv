import { afterEach, beforeEach, describe, expect, it, vi } from "vitest"
import { defineComponent, h, ref } from "vue"
import { CountUp, type CountUpEasing, type CountUpRenderState } from "../src/components/CountUp.js"
import { mountHost } from "./harness.js"
import type { HostNode } from "@gpuiv/vue"

const hosts: ReturnType<typeof mountHost>[] = []
const mount = (props: Parameters<typeof h>[1] = {}) => {
  const host = mountHost(defineComponent(() => () => h(CountUp, { end: 100, testId: "score", ...props })))
  hosts.push(host)
  return host
}
const subtreeText = (node: HostNode): string => (node.text ?? "") + node.children.map(subtreeText).join("")
const number = (host: ReturnType<typeof mountHost>) => subtreeText(host.find("score-number"))
beforeEach(() => { vi.useFakeTimers(); vi.setSystemTime(0) })
afterEach(() => { hosts.splice(0).forEach(host => host.unmount()); vi.useRealTimers() })

describe("React CountUp parity", () => {
  it("holds the start value until counting begins and exposes a readable status", () => {
    const host = mount({ start: 42 })
    expect(number(host)).toBe("42")
    expect(host.find("score").props).toMatchObject({ role: "status", "aria-valuetext": "42" })
    expect(vi.getTimerCount()).toBe(0)
  })
  it("animates values and finishes once with the actual elapsed seconds", async () => {
    const onUpdate = vi.fn(), onComplete = vi.fn()
    const host = mount({ isCounting: true, duration: 1, easing: "linear", onUpdate, onComplete })
    await host.settle()
    expect(host.find("score").props["aria-valuetext"]).toBe("")
    await vi.advanceTimersByTimeAsync(500)
    await host.settle()
    expect(Number(number(host))).toBeGreaterThan(40)
    expect(Number(number(host))).toBeLessThan(60)
    await vi.advanceTimersByTimeAsync(600)
    await host.settle()
    expect(number(host)).toBe("100")
    expect(onUpdate).toHaveBeenLastCalledWith(100)
    expect(onComplete).toHaveBeenCalledOnce()
    expect(onComplete.mock.calls[0][0]).toBeGreaterThanOrEqual(1)
    expect(host.find("score").props["aria-valuetext"]).toBe("100")
    expect(vi.getTimerCount()).toBe(0)
  })
  it("duration zero formats immediately and supports arbitrary prefix/suffix content", async () => {
    const host = mount({ isCounting: true, duration: 0, end: 1234.5, decimalPlaces: 2, decimalSeparator: ",", thousandsSeparator: ".", prefix: h("text", "¥"), suffix: "分" })
    await host.settle()
    expect(number(host)).toBe("1.234,50")
    expect(host.text()).toContain("¥")
    expect(host.text()).toContain("分")
  })
  it("infers decimal places including scientific notation", async () => {
    const host = mount({ isCounting: true, duration: 0, start: 1e-7, end: 2e-7 })
    await host.settle()
    expect(number(host)).toBe("0.0000002")
  })
  it("formatter takes precedence but the accessible value remains numeric", async () => {
    const host = mount({ isCounting: true, duration: 0, formatter: (value: number) => h("text", `分数 ${value}`) })
    await host.settle()
    expect(number(host)).toBe("分数 100")
    expect(host.find("score").props["aria-valuetext"]).toBe("100")
  })
  it("allows a custom formatter to intentionally render no visible content", async () => {
    const host = mount({ isCounting: true, duration: 0, formatter: () => null })
    await host.settle()
    expect(number(host)).toBe("")
    expect(host.find("score").props["aria-valuetext"]).toBe("100")
  })
  it("normalizes boolean and list-valued formatter/affix content like React", async () => {
    const host = mount({ isCounting: true, duration: 0, formatter: () => false, prefix: false, suffix: [false, h("text", "分")] })
    await host.settle()
    expect(number(host)).toBe("")
    expect(host.text()).toBe("分")
    expect(host.text()).not.toContain("false")
  })
  it.each(["linear", "easeInCubic", "easeOutCubic", "easeInOutCubic", "easeOutExpo", "unknown", (p: number) => p ** 2] as CountUpEasing[])("reaches the end using easing %s", async easing => {
    const host = mount({ isCounting: true, duration: .1, easing })
    await vi.advanceTimersByTimeAsync(120)
    await host.settle()
    expect(number(host)).toBe("100")
  })
  it("quantizes display time while still calling onUpdate every sample", async () => {
    const onUpdate = vi.fn()
    const host = mount({ isCounting: true, duration: 1, easing: "linear", updateInterval: 1, onUpdate })
    await vi.advanceTimersByTimeAsync(500)
    await host.settle()
    expect(number(host)).toBe("0")
    expect(onUpdate.mock.calls.length).toBeGreaterThan(20)
    await vi.advanceTimersByTimeAsync(600)
    await host.settle()
    expect(number(host)).toBe("100")
  })
  it("does not send redundant text mutations when the formatted output is unchanged", async () => {
    const host = mount({ isCounting: true, duration: 100, easing: "linear", end: 1 })
    const batches = vi.spyOn(host.native, "applyBatch")
    await host.settle()
    batches.mockClear()
    await vi.advanceTimersByTimeAsync(500)
    await host.settle()
    expect(batches).not.toHaveBeenCalled()
    batches.mockRestore()
  })
  it("pauses without advancing the elapsed time and resumes at the current value", async () => {
    const running = ref(true)
    const host = mountHost(defineComponent(() => () => h(CountUp, { end: 100, duration: 1, easing: "linear", isCounting: running.value, testId: "score" })))
    hosts.push(host)
    await vi.advanceTimersByTimeAsync(400)
    await host.settle()
    const paused = number(host)
    running.value = false
    await host.settle()
    expect(vi.getTimerCount()).toBe(0)
    await vi.advanceTimersByTimeAsync(1000)
    expect(number(host)).toBe(paused)
    running.value = true
    await host.settle()
    await vi.advanceTimersByTimeAsync(300)
    await host.settle()
    expect(Number(number(host))).toBeGreaterThan(Number(paused))
    expect(Number(number(host))).toBeLessThan(100)
  })
  it("restarts on target changes and cancels a pending repeat", async () => {
    const end = ref(10), duration = ref(0)
    const onComplete = vi.fn().mockReturnValueOnce({ shouldRepeat: true, delay: .5 })
    const host = mountHost(defineComponent(() => () => h(CountUp, { end: end.value, duration: duration.value, isCounting: true, onComplete, testId: "score" })))
    hosts.push(host)
    expect(onComplete).toHaveBeenCalledOnce()
    end.value = 20; duration.value = .1
    await host.settle()
    expect(number(host)).toBe("0")
    await vi.advanceTimersByTimeAsync(700)
    await host.settle()
    expect(number(host)).toBe("20")
    expect(onComplete).toHaveBeenCalledTimes(2)
    expect(vi.getTimerCount()).toBe(0)
  })
  it("supports render functions with reset(newStartAt) over the entire new run", async () => {
    let state: CountUpRenderState | undefined
    const host = mount({ isCounting: true, duration: 1, easing: "linear", children: (next: CountUpRenderState) => { state = next; return `v${Math.round(next.value)}` } })
    await vi.advanceTimersByTimeAsync(1100)
    await host.settle()
    expect(number(host)).toBe("v100")
    state!.reset(50)
    await host.settle()
    expect(number(host)).toBe("v50")
    await vi.advanceTimersByTimeAsync(500)
    await host.settle()
    expect(Number(number(host).slice(1))).toBeGreaterThan(70)
    expect(Number(number(host).slice(1))).toBeLessThan(80)
  })
  it("repeats after the callback delay and releases all work on unmount", async () => {
    const onComplete = vi.fn().mockReturnValue({ shouldRepeat: true, delay: .5, newStartAt: 50 })
    const host = mount({ isCounting: true, duration: .1, onComplete })
    await vi.advanceTimersByTimeAsync(120)
    await host.settle()
    expect(number(host)).toBe("100")
    await vi.advanceTimersByTimeAsync(480)
    await host.settle()
    expect(onComplete).toHaveBeenCalledOnce()
    await vi.advanceTimersByTimeAsync(12)
    await host.settle()
    expect(number(host)).toBe("50")
    host.unmount(); hosts.pop()
    expect(vi.getTimerCount()).toBe(0)
  })
  it("celebrates with native motion and temporary VNode stickers, then clears them", async () => {
    const host = mount({ isCounting: true, duration: .1, celebrate: { text: h("text", "完美！") }, variant: "island", size: "large", bordered: true })
    await vi.advanceTimersByTimeAsync(120)
    await host.settle()
    expect(host.text()).toContain("完美！")
    expect(host.find("score-celebration").props.style).toMatchObject({ pointerEvents: "none" })
    expect(host.find("score").props.style).toMatchObject({ minHeight: 56, backgroundColor: "#f7f3df", borderWidth: 2 })
    expect(host.all().some(node => (node.props.motion as { animate?: { opacity?: number } } | undefined)?.animate?.opacity === 0)).toBe(true)
    await vi.advanceTimersByTimeAsync(1000)
    await host.settle()
    expect(host.text()).not.toContain("完美！")
    // The island border continues to measure while its component is mounted.
    host.unmount(); hosts.pop()
    expect(vi.getTimerCount()).toBe(0)
  })
})
